"""Train and export the fully connected MNIST layer used by the C++ testbench."""

from pathlib import Path
import re

import numpy as np
from sklearn.linear_model import LogisticRegression


IMAGE_SIZE = 28
FEATURE_SIZE = 5408
CLASS_COUNT = 10


def read_declared_array(header_text, declaration):
    match = re.search(rf"{re.escape(declaration)}\s*=\s*\{{([^}}]*)\}};", header_text)
    if match is None:
        raise ValueError(f"Could not find {declaration}")
    values = re.findall(r"[-+]?(?:\d+\.?(?:\d*)?|\.\d+)(?:[eE][-+]?\d+)?", match.group(1))
    return np.asarray([float(value) for value in values], dtype=np.float32)


def load_dataset(dataset_dir):
    images = []
    labels = []
    for label in range(CLASS_COUNT):
        for image_path in sorted((dataset_dir / str(label)).glob("*.txt")):
            values = np.fromstring(image_path.read_text(), sep=",")
            if values.size != IMAGE_SIZE * IMAGE_SIZE:
                raise ValueError(f"{image_path} contains {values.size} values, expected 784")
            images.append(values.reshape(IMAGE_SIZE, IMAGE_SIZE))
            labels.append(label)
    if not images:
        raise ValueError(f"No images found in {dataset_dir}")
    return np.asarray(images, dtype=np.float32), np.asarray(labels, dtype=np.int64)


def extract_features(images, convolution_weights, convolution_bias):
    windows = np.lib.stride_tricks.sliding_window_view(
        images, (3, 3), axis=(1, 2)  # type: ignore[arg-type]
    )
    convolution = np.einsum("nijab,abk->nijk", windows, convolution_weights, optimize=True)
    convolution = convolution.reshape(images.shape[0], 26, 26, 32)
    convolution = np.maximum(convolution + convolution_bias, 0.0)
    pooled = convolution.reshape(images.shape[0], 13, 2, 13, 2, 32).max(axis=(2, 4))
    return pooled.reshape(images.shape[0], FEATURE_SIZE)


def train(features, labels):
    classifier = LogisticRegression(C=10.0, max_iter=1000, solver="lbfgs")
    classifier.fit(features, labels)
    accuracy = classifier.score(features, labels)
    print(f"training_accuracy={accuracy:.4f}")
    return classifier.coef_.T.astype(np.float32), classifier.intercept_.astype(np.float32)


def write_header(output_path, weights, bias):
    with output_path.open("w", encoding="utf-8", newline="\n") as output:
        output.write("#ifndef CNN_XILINX_FC_WEIGHTS_H\n#define CNN_XILINX_FC_WEIGHTS_H\n\n")
        output.write("// Generated by tools/train_fc.py.\n")
        output.write("float fc_weights[5408][10] = {\n")
        for row in weights:
            output.write("    {" + ",".join(f"{value:.9e}f" for value in row) + "},\n")
        output.write("};\n\n")
        output.write("float fc_bias[10] = {" + ",".join(f"{value:.9e}f" for value in bias) + "};\n\n")
        output.write("#endif // CNN_XILINX_FC_WEIGHTS_H\n")


def main():
    project_dir = Path(__file__).resolve().parents[1]
    convolution_header = (project_dir / "testbench" / "conv_weights.h").read_text(encoding="utf-8")
    convolution_bias = read_declared_array(convolution_header, "float conv_bias[32]")
    convolution_weights = read_declared_array(
        convolution_header, "float conv_weights[3][3][1][32]"
    ).reshape(3, 3, 32)
    images, labels = load_dataset(project_dir / "testbench" / "mnist_txt_1000")
    features = extract_features(images, convolution_weights, convolution_bias)
    weights, bias = train(features, labels)
    write_header(project_dir / "testbench" / "fc_weights.h", weights, bias)
    print(f"exported={project_dir / 'testbench' / 'fc_weights.h'} samples={len(labels)}")


if __name__ == "__main__":
    main()